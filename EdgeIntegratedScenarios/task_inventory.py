"""Generate a deterministic Markdown inventory from repository TASK.md files."""
import argparse
from dataclasses import dataclass, field
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUTPUT = HERE / "TASK-INVENTORY.md"
TASK = re.compile(r"#\s+((?:EAI|EIS|ENS)-\d+(?:-[A-Z]+)?)\s+—\s+(.+)")
CHECKBOX = re.compile(r"\s*[-*]\s+\[ \]\s+(.+)")
TODO = re.compile(r"(?:^|(?<=\.\s))(?:Next )?TODO(?: next| later| for Codex)?\s*\**:\s*(.+)", re.I)
LINK = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")

BLOCKED = {"EAI-03", "EAI-04", "ENS-05", "ENS-06", "ENS-07"}
# ENS-04 summarizes these Redis work items. Keep the detailed entry and both links.
REDIS_OVERLAPS = {
    "sliding-window/token bucket comparison": "evaluate sliding-window/token-bucket",
    "trusted reverse proxy, known-proxy": "trusted reverse proxy and origin-only",
    "distributed concurrency control": "true distributed concurrency limiter",
    "opentelemetry/prometheus counters": "opentelemetry/prometheus instrumentation",
    "container/compose with secure redis": "build a container/compose topology",
}


@dataclass
class Task:
    title: str
    sources: list = field(default_factory=list)
    followups: dict = field(default_factory=dict)


def source_record(line):
    text = line.strip().replace("**", "")
    match = CHECKBOX.fullmatch(text)
    if match:
        body = match[1]
        # Cross-references to another task document are navigation.
        if not any(Path(url).name == "TASK.md" for _, url in LINK.findall(body)):
            return body
    match = TODO.search(text)
    if match:
        return match[1]


def collect(paths):
    tasks = {}
    for path in sorted(paths):
        current = None
        fence = None
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            marker = re.match(r"^\s*(`{3,}|~{3,})", line)
            if marker:
                delimiter = marker[1]
                if fence is None:
                    fence = delimiter
                elif delimiter[0] == fence[0] and len(delimiter) >= len(fence):
                    fence = None
                continue
            if fence:
                continue
            heading = TASK.fullmatch(line)
            if heading:
                identifier, title = heading.groups()
                current = tasks.setdefault(identifier, Task(title))
                if current.title != title:
                    raise ValueError(f"conflicting title for {identifier}")
                current.sources.append((path, number))
            elif current and (action := source_record(line)):
                plain = LINK.sub(r"\1", action)
                key = " ".join(plain.replace("`", "").rstrip(".").casefold().split())
                _, locations = current.followups.setdefault(key, (plain, []))
                locations.append((path, number))
    if "ENS-04" in tasks and "ENS-04-R" in tasks:
        parent = tasks["ENS-04"].followups
        redis = tasks["ENS-04-R"].followups
        for summary, detail in REDIS_OVERLAPS.items():
            source = next((key for key in parent if key.startswith(summary)), None)
            target = next((key for key in redis if key.startswith(detail)), None)
            if source and target:
                redis[target][1].extend(parent.pop(source)[1])
    return tasks


def reference(path, line):
    relative = path.relative_to(ROOT)
    target = relative.relative_to(HERE.name) if relative.parts[0] == HERE.name else Path("..") / relative
    return f"[{relative}:{line}]({target}#L{line})"


def render(tasks):
    lines = [
        "# Edge task inventory", "",
        "Generated by `python3 -B EdgeIntegratedScenarios/task_inventory.py`.",
        "Each numbered task appears once. Source documents carry completion and acceptance details.",
        "Open checkboxes and explicit TODO directives are indexed under their task.",
        "Repeated wording and overlapping ENS-04 Redis follow-ups are listed once, with source links.",
        "Status words, incidental TODO mentions, completed checkboxes and links to other task files",
        "do not create additional entries.", "",
    ]
    for identifier, task in sorted(tasks.items()):
        lines.extend([f"## {identifier} — {task.title}", "",
                      ", ".join(reference(*location) for location in task.sources), ""])
        if identifier in BLOCKED:
            lines.extend(["**Blocked in EIS** pending external provider prerequisites.", ""])
        for action, locations in task.followups.values():
            lines.append(f"- {action} " + ", ".join(reference(*location) for location in locations))
        if task.followups:
            lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the checked-in inventory")
    args = parser.parse_args()
    paths = (path for directory in ("EdgeAI", "EdgeNetworkSecurity", HERE.name)
             for path in (ROOT / directory).rglob("TASK.md") if not path.is_symlink())
    generated = render(collect(paths))
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != generated:
            print("Task inventory is stale", file=sys.stderr)
            return 1
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
